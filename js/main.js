document.querySelectorAll(".main-nav a").forEach((link) => {
  const current = window.location.pathname.split("/").pop() || "index.html";
  if (link.getAttribute("href") === current) link.classList.add("active");
});

function getLang() {
  return localStorage.getItem("siteLang") || "en";
}

function setLang(lang) {
  localStorage.setItem("siteLang", lang);
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (translations[lang][key]) node.textContent = translations[lang][key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    if (translations[lang][key]) node.placeholder = translations[lang][key];
  });
  document.querySelectorAll("[data-lang-toggle]").forEach((button) => {
    button.textContent = lang === "zh" ? "EN" : "中文";
  });
  renderProducts();
}

function productsForLang() {
  const lang = getLang();
  return productData.map(([enName, zhName, enCat, zhCat, image, enDesc, zhDesc]) => ({
    name: lang === "zh" ? zhName : enName,
    category: lang === "zh" ? zhCat : enCat,
    image,
    description: lang === "zh" ? zhDesc : enDesc
  }));
}

function productCard(product) {
  const inquiryUrl = `contact.html?product=${encodeURIComponent(product.name)}`;
  return `<article class="product-card"><img src="${product.image}" alt="${product.name}"><div><span class="tag">${product.category}</span><h3>${product.name}</h3><p>${product.description}</p><a class="btn primary" href="${inquiryUrl}">${translations[getLang()].quote_now}</a></div></article>`;
}

function renderProducts() {
  const products = productsForLang();
  const featured = document.getElementById("featuredProducts");
  if (featured) featured.innerHTML = products.slice(0, 4).map(productCard).join("");

  const catalog = document.getElementById("productCatalog");
  const search = document.getElementById("productSearch");
  const filters = document.getElementById("categoryFilters");
  if (!catalog) return;

  if (filters && !filters.dataset.ready) {
    filters.addEventListener("click", (event) => {
      const button = event.target.closest("button");
      if (!button) return;
      filters.querySelectorAll("button").forEach((item) => item.classList.remove("active"));
      button.classList.add("active");
      renderProducts();
    });
    filters.dataset.ready = "true";
  }
  if (search && !search.dataset.ready) {
    search.addEventListener("input", renderProducts);
    search.dataset.ready = "true";
  }

  const categories = ["All", ...new Set(products.map((item) => item.category))];
  const active = filters?.querySelector(".active")?.dataset.category || "All";
  if (filters) {
    filters.innerHTML = categories.map((category) => `<button type="button" class="${category === active ? "active" : ""}" data-category="${category}">${category === "All" && getLang() === "zh" ? "全部" : category}</button>`).join("");
  }

  const keyword = search ? search.value.trim().toLowerCase() : "";
  const selected = filters?.querySelector(".active")?.dataset.category || "All";
  const filtered = products.filter((item) => {
    const categoryMatch = selected === "All" || item.category === selected;
    const textMatch = `${item.name} ${item.category} ${item.description}`.toLowerCase().includes(keyword);
    return categoryMatch && textMatch;
  });
  catalog.innerHTML = filtered.length ? filtered.map(productCard).join("") : `<p>${translations[getLang()].no_products}</p>`;
}

